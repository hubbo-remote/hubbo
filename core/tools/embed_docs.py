#!/usr/bin/env python3
"""Embed the agent docs (the OpenAPI spec and the agent guide) in a build.

    embed_docs.py <api/openapi.yaml> <docs/agent-api.md> <docs/llms.txt> <out.cpp>

Writes a C++ source defining hubbo::api::docs::kOpenApiJson (the spec as
compact JSON) and kAgentGuide (the guide's exact bytes), each raw and gzipped
with an ETag, and kLlmsTxt (llms.txt's exact text), as declared in core/include/hubbo/api/agent_docs.h. Generated
from the repo copies on every build, so the hub serves what the repo says.
Needs PyYAML: core's CMake runs it for hub-sim and the tests, and the
firmware's PlatformIO build runs it too.
"""
import gzip
import hashlib
import json
import sys

import yaml

sys.dont_write_bytecode = True  # no __pycache__ in the repo from the import below
from embed_profiles import literal, write_if_changed  # noqa: E402


def doc(name: str, raw: bytes) -> str:
    packed = gzip.compress(raw, compresslevel=9, mtime=0)  # mtime 0: the same bytes every build
    etag = '"%s"' % hashlib.sha256(raw).hexdigest()[:16]
    return "const Doc %s = {\n    %s,\n    %d,\n    %s,\n    %d,\n    %s};\n" % (
        name, literal(raw), len(raw), literal(packed), len(packed), literal(etag.encode()))


def main(argv):
    if len(argv) != 5:
        sys.stderr.write(__doc__)
        return 2
    spec_path, guide_path, llms_path, dst = argv[1:]
    with open(spec_path, "rb") as f:
        spec = yaml.load(f, Loader=getattr(yaml, "CSafeLoader", yaml.SafeLoader))  # libyaml when there
    spec_json = json.dumps(spec, separators=(",", ":"), ensure_ascii=False,
                           default=lambda v: v.isoformat()).encode("utf-8")  # YAML dates
    with open(guide_path, "rb") as f:
        guide = f.read()
    with open(llms_path, "rb") as f:
        llms = f.read()
    write_if_changed(dst, "\n".join([
        "// Generated by core/tools/embed_docs.py from api/openapi.yaml, docs/agent-api.md and docs/llms.txt."
        " Don't edit.",
        '#include "hubbo/api/agent_docs.h"',
        "",
        "namespace hubbo::api::docs {",
        "",
        doc("kOpenApiJson", spec_json),
        doc("kAgentGuide", guide),
        "const char kLlmsTxt[] =\n    %s;\n" % literal(llms),
        "}  // namespace hubbo::api::docs",
        "",
    ]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
