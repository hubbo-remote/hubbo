#!/usr/bin/env python3
"""Embed the built-in profiles in a build.

    embed_profiles.py <profiles dir> <out.cpp>

Writes a C++ source defining hubbo::config::kBuiltinProfileFiles (one
{name, text} per *.json file in the directory, sorted by name) and
kBuiltinProfileFileCount, as declared in core/include/hubbo/config/profile.h.
Plain python3, no dependencies: core's CMake runs it for hub-sim and the
tests, and the firmware's PlatformIO build runs it too.
"""
import os
import sys


def literal(data: bytes) -> str:
    lines = []
    out = []
    for b in data:
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
            lines.append('"' + "".join(out) + '"')
            out = []
        elif 32 <= b < 127 and c != "?":  # "?" avoids trigraphs
            out.append(c)
        else:
            out.append("\\%03o" % b)
    if out or not lines:
        lines.append('"' + "".join(out) + '"')
    return "\n        ".join(lines)


def write_if_changed(dst: str, text: str) -> None:
    """Leaves an unchanged file alone, so nothing rebuilds."""
    try:
        with open(dst, "r", encoding="utf-8") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(dst, "w", encoding="utf-8") as f:
        f.write(text)


def main(argv):
    if len(argv) != 3:
        sys.stderr.write(__doc__)
        return 2
    src, dst = argv[1], argv[2]
    names = sorted(n for n in os.listdir(src) if n.endswith(".json"))
    parts = [
        "// Generated by core/tools/embed_profiles.py from " + os.path.basename(os.path.normpath(src)) + "/. Don't edit.",
        '#include "hubbo/config/profile.h"',
        "",
        "namespace hubbo::config {",
        "",
    ]
    entries = []
    for name in names:
        with open(os.path.join(src, name), "rb") as f:
            entries.append('    {"%s",\n        %s},' % (name, literal(f.read())))
    if entries:
        parts.append("const ProfileFile kBuiltinProfileFiles[] = {")
        parts.extend(entries)
        parts.append("};")
        parts.append("const size_t kBuiltinProfileFileCount = %d;" % len(entries))
    else:
        parts.append("const ProfileFile kBuiltinProfileFiles[1] = {{nullptr, nullptr}};")
        parts.append("const size_t kBuiltinProfileFileCount = 0;")
    parts.extend(["", "}  // namespace hubbo::config", ""])
    write_if_changed(dst, "\n".join(parts))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
