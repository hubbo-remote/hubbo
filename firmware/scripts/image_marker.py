# PlatformIO pre-build script: the Hubbo image marker, a string every Hubbo
# image carries so a firmware update can tell it from any other app image:
#
#   HUBBO-IMAGE/1 board=<board::kName> layout=<board::kLayout> version=<git describe>
#
# HUBBO_FW_VERSION, if set, replaces git describe: the release workflow and
# `gate fw`'s plain-env build. Unset (a dev build), the build also defines
# HUBBO_REMOTE_LOG for our sources and core (docs/design/remote-log.md).
#
# Generated into the build directory as image_marker.cpp, compiled with the
# sources, and rewritten only when the version changes (no full rebuild per
# commit, unlike a global define). After the link, the .bin is checked to
# hold the marker, so a linker that dropped it fails the build.

import os
import re
import subprocess
import sys

Import("env")  # noqa: F821 (SCons)

PROJECT = env.subst("$PROJECT_DIR")  # noqa: F821
GEN_DIR = os.path.join(env.subst("$BUILD_DIR"), "image_gen")  # noqa: F821
FW_VERSION = os.environ.get("HUBBO_FW_VERSION", "")
MARKER = re.compile(rb"HUBBO-IMAGE/1 board=[!-~]+ layout=[0-9]{1,4} version=[!-~]{1,64}\0")


def build_version():
    # HUBBO_FW_VERSION overrides git describe; unset or empty means git describe.
    if FW_VERSION:
        return sanitize(FW_VERSION)
    try:
        out = subprocess.run(["git", "-C", PROJECT, "describe", "--tags", "--always", "--dirty"],
                             capture_output=True, text=True, timeout=10)
        version = out.stdout.strip() if out.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        version = ""
    return sanitize(version)


def sanitize(version):
    # The marker's version is printable ASCII without spaces, at most 64 chars.
    version = re.sub(r"[^!-~]", "_", version)[:64]
    return version or "unknown"


def generate(version):
    header = os.path.join(env.subst("$PROJECT_SRC_DIR"), "image_marker.h")  # noqa: F821
    board = os.path.join(env.subst("$PROJECT_SRC_DIR"), "board.h")  # noqa: F821
    text = "\n".join([
        "// Generated by firmware/scripts/image_marker.py. Do not edit.",
        '#include "%s"' % header,
        '#include "%s"' % board,
        "",
        "#include <cstring>",
        "",
        "#define HUBBO_STR_(x) #x",
        "#define HUBBO_STR(x) HUBBO_STR_(x)",
        "",
        "namespace hubbo::fw::image {",
        "",
        "// `used`: kept even though only version() reads it.",
        "__attribute__((used)) const char kMarker[] = \"HUBBO-IMAGE/1 board=\" HUBBO_BOARD_NAME",
        "    \" layout=\" HUBBO_STR(HUBBO_PARTITION_LAYOUT) \" version=%s\";" % version,
        "",
        "const char *version() { return std::strstr(kMarker, \" version=\") + sizeof(\" version=\") - 1; }",
        "",
        "}  // namespace hubbo::fw::image",
        "",
    ])
    os.makedirs(GEN_DIR, exist_ok=True)
    out = os.path.join(GEN_DIR, "image_marker.cpp")
    old = open(out).read() if os.path.exists(out) else None
    if text != old:
        with open(out, "w") as f:
            f.write(text)
    print("image marker: version %s" % version)


def check_bin(target, source, env):  # noqa: ARG001 (SCons signature)
    path = str(target[0])
    with open(path, "rb") as f:
        found = MARKER.findall(f.read())
    if len(found) != 1:
        sys.stderr.write("\n*** image marker: %s holds %d markers, expected 1\n\n" % (path, len(found)))
        env.Exit(1)
    print("image marker: %s" % found[0][:-1].decode())


if not FW_VERSION:
    env.Append(CPPDEFINES=[("HUBBO_REMOTE_LOG", 1)])  # noqa: F821
    print("remote log: on (dev build)")
generate(build_version())
env.BuildSources(os.path.join("$BUILD_DIR", "image_obj"), GEN_DIR)  # noqa: F821
env.AddPostAction("$BUILD_DIR/${PROGNAME}.bin", check_bin)  # noqa: F821
