# PlatformIO pre-build script: the release signing public key
# (docs/design/firmware-updates.md). firmware/release-key.pub.pem is the one
# source: the firmware verifies manifest.sig with it, and the release workflow
# checks each signature against the same file.
#
# Generated into the build directory as release_key.cpp (src/release_key.h is
# its interface), rewritten only when the key changes.
#
# Local tests: HUBBO_TEST_RELEASE_KEY_FILE (a PEM path, relative to the repo
# or absolute) adds one test key, accepted only by dev-console (_ota) builds.
# Unset, or another env: no test key.

import os
import re
import sys

Import("env")  # noqa: F821 (SCons)

PROJECT = env.subst("$PROJECT_DIR")  # noqa: F821
KEY = os.path.join(PROJECT, "release-key.pub.pem")
GEN_DIR = os.path.join(env.subst("$BUILD_DIR"), "release_key_gen")  # noqa: F821
PEM = re.compile(r"-----BEGIN PUBLIC KEY-----\n[A-Za-z0-9+/=\n]+-----END PUBLIC KEY-----\n")


def read_pem(path):
    with open(path) as f:
        pem = f.read()
    if not PEM.fullmatch(pem):
        sys.stderr.write("\n*** release key: %s isn't one PEM public key\n\n" % path)
        env.Exit(1)  # noqa: F821
    return "".join('    "%s\\n"\n' % line for line in pem.splitlines())


def test_key():
    path = os.environ.get("HUBBO_TEST_RELEASE_KEY_FILE", "")
    if not path:
        return None
    if "HUBBO_DEV_CONSOLE" not in env.subst("$BUILD_FLAGS"):  # noqa: F821
        print("release key: HUBBO_TEST_RELEASE_KEY_FILE ignored (not a dev build)")
        return None
    path = path if os.path.isabs(path) else os.path.join(PROJECT, "..", path)
    print("*** release key: this dev build also accepts the test key %s ***" % path)
    return read_pem(path)


def generate():
    header = os.path.join(env.subst("$PROJECT_SRC_DIR"), "release_key.h")  # noqa: F821
    test = test_key()
    text = "".join([
        "// Generated by firmware/scripts/release_key.py from release-key.pub.pem. Do not edit.\n",
        '#include "%s"\n\n' % header,
        "namespace hubbo::fw::release_key {\n\n",
        "const char kPem[] =\n", read_pem(KEY), "    ;\n\n",
        "const char *const kTestPem =\n" + test + "    ;\n\n" if test else "const char *const kTestPem = nullptr;\n\n",
        "}  // namespace hubbo::fw::release_key\n",
    ])
    os.makedirs(GEN_DIR, exist_ok=True)
    out = os.path.join(GEN_DIR, "release_key.cpp")
    old = open(out).read() if os.path.exists(out) else None
    if text != old:
        with open(out, "w") as f:
            f.write(text)


generate()
env.BuildSources(os.path.join("$BUILD_DIR", "release_key_obj"), GEN_DIR)  # noqa: F821
