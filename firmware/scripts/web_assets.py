# PlatformIO pre-build script: packs the web admin (web/dist, from
# `bin/hubbo web build`) into the firmware image as a generated .cpp in the
# build directory, compiled with the sources. Nothing generated lands in git.
#
# Per file: gzip -9 with mtime 0 (the same dist gives the same bytes), the
# content type, and whether it's a hashed (immutable) asset under /a/. Plus
# an ETag over the whole dist and the CSP, with the SHA-256 of each inline
# <script> in index.html (the theme script) so no 'unsafe-inline' is needed.
#
# A missing web/dist fails the build: run `bin/hubbo web build` first
# (bin/hubbo fw / ota do).

import base64
import gzip
import hashlib
import os
import re
import sys

Import("env")  # noqa: F821  (SCons)

PROJECT = env.subst("$PROJECT_DIR")  # noqa: F821
DIST = os.path.normpath(os.path.join(PROJECT, "..", "web", "dist"))
GEN_DIR = os.path.join(env.subst("$BUILD_DIR"), "web_gen")  # noqa: F821

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".webp": "image/webp",
    ".woff2": "font/woff2",
    ".json": "application/json",
    ".webmanifest": "application/manifest+json",
    ".txt": "text/plain; charset=utf-8",
}


def fail(message):
    sys.stderr.write("\n*** web assets: %s\n\n" % message)
    env.Exit(1)  # noqa: F821


def collect():
    if not os.path.isfile(os.path.join(DIST, "index.html")):
        fail("%s/index.html is missing. Run `bin/hubbo web build` first." % DIST)
    files = []
    for root, _, names in os.walk(DIST):
        for name in names:
            full = os.path.join(root, name)
            path = "/" + os.path.relpath(full, DIST).replace(os.sep, "/")
            ext = os.path.splitext(name)[1].lower()
            if ext == ".map":
                continue  # source maps stay off the board
            if ext not in TYPES:
                fail("%s: no content type for %s" % (path, ext))
            with open(full, "rb") as f:
                files.append((path, f.read()))
    return sorted(files)


def csp(index_html):
    hashes = []
    for script in re.findall(rb"<script>(.*?)</script>", index_html, re.S):
        digest = base64.b64encode(hashlib.sha256(script).digest()).decode()
        hashes.append("'sha256-%s'" % digest)
    # The catalog origin in connect-src must match the web admin's catalog URL
    # (web/src/lib/catalog.ts).
    return ("default-src 'self'; script-src 'self' %s; style-src 'self' 'unsafe-inline'; "
            "img-src 'self' data:; connect-src 'self' https://catalog.hubbo.tv; object-src 'none'; base-uri 'none'; "
            "form-action 'self'; frame-ancestors 'none'" % " ".join(hashes))


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate():
    files = collect()
    whole = hashlib.sha256()
    header = os.path.join(env.subst("$PROJECT_SRC_DIR"), "web_assets.h")  # noqa: F821
    lines = ['// Generated by firmware/scripts/web_assets.py from web/dist. Do not edit.',
             '#include "%s"' % header, '', 'namespace hubbo::fw::web {', 'namespace {', '']
    entries = []
    total = 0
    for i, (path, data) in enumerate(files):
        whole.update(path.encode() + b"\0" + data)
        packed = gzip.compress(data, compresslevel=9, mtime=0)
        total += len(packed)
        body = ",".join(str(b) for b in packed)
        lines.append("const uint8_t k%d[] = {%s};" % (i, body))
        ext = os.path.splitext(path)[1].lower()
        immutable = "true" if path.startswith("/a/") else "false"
        entries.append("    {%s, %s, k%d, sizeof(k%d), %s}," % (c_string(path), c_string(TYPES[ext]), i, i,
                                                                 immutable))
    index = dict(files)["/index.html"]
    lines += ["", "const Asset kAssets[] = {"] + entries + ["};", "", "}  // namespace", ""]
    lines.append("const char kEtag[] = %s;" % c_string('"%s"' % whole.hexdigest()[:16]))
    lines.append("const char kCsp[] = %s;" % c_string(csp(index)))
    lines += ["", "const Asset *find(std::string_view path) {",
              "    for (const Asset &asset : kAssets) {",
              "        if (path == asset.path) return &asset;",
              "    }",
              "    return nullptr;",
              "}", "", "}  // namespace hubbo::fw::web", ""]
    os.makedirs(GEN_DIR, exist_ok=True)
    out = os.path.join(GEN_DIR, "web_assets.cpp")
    text = "\n".join(lines)
    old = open(out).read() if os.path.exists(out) else None
    if text != old:  # unchanged dist: no rebuild
        with open(out, "w") as f:
            f.write(text)
    print("web assets: %d files, %d bytes gzipped, etag %s" % (len(files), total, whole.hexdigest()[:16]))


generate()
env.BuildSources(os.path.join("$BUILD_DIR", "web_obj"), GEN_DIR)  # noqa: F821
